"""Reproducible Monte Carlo model for the digitalisation risk scenarios.

Method
------
Compound-Poisson loss model (FAIR-style frequency x magnitude):

* Frequency  : for each scenario the number of loss events in one year is
  Poisson with rate lambda = -ln(1 - p), so P(at least one event) = p.
* Dependence : cyber-attack and logistics-disruption frequencies are joined by
  a Gaussian copula (latent bivariate normal, correlation RHO) so the two can
  coincide during peak trading periods. The copula leaves each marginal Poisson
  exactly as elicited; only the dependence is added.
* Magnitude  : severity per event is lognormal (median in EUR, dispersion sigma).

Everything is seeded, so every figure quoted in the executive summary can be
regenerated by re-running this file with Python 3 + NumPy.
"""

import math
import numpy as np

SEED = 42
N = 200_000          # iterations
RHO = 0.55           # copula correlation -> ~0.3 Spearman on Poisson margins
KMAX = 60            # support of the Poisson quantile

rng = np.random.default_rng(SEED)

# name, annual P(>=1 event), severity median (EUR), severity log-sigma
scenarios = [
    ("Quality: cold-chain / sensor failure",       0.064,   800_000, 0.70),
    ("Quality: loss of craft oversight",           0.112,   350_000, 0.60),
    ("Supply: cyber-attack / ransomware",          0.175, 1_400_000, 0.80),
    ("Supply: key-supplier dependency failure",    0.210,   500_000, 0.55),
    ("Supply: logistics / congestion disruption",  0.148,   600_000, 0.60),
    ("Supply: data-integrity corruption",          0.096,   400_000, 0.60),
]

_erf = np.frompyfunc(math.erf, 1, 1)


def norm_cdf(z):
    return (0.5 * (1.0 + _erf(z / math.sqrt(2.0)))).astype(float)


def poisson_cdf(lam):
    cdf = np.empty(KMAX + 1)
    term = math.exp(-lam)          # P(K = 0)
    acc = term
    cdf[0] = acc
    for k in range(1, KMAX + 1):
        term *= lam / k
        acc += term
        cdf[k] = acc
    return np.minimum(cdf, 1.0)


# latent normals; indices 2 and 4 share a copula correlation
z = rng.standard_normal((N, len(scenarios)))
zc = RHO * z[:, 2] + math.sqrt(1.0 - RHO ** 2) * rng.standard_normal(N)
z[:, 4] = zc

U = norm_cdf(z)

counts = np.zeros((N, len(scenarios)), dtype=int)
loss = np.zeros((N, len(scenarios)), dtype=float)

for i, (name, p, median, sigma) in enumerate(scenarios):
    lam = -math.log(1.0 - p)
    cdf = poisson_cdf(lam)
    counts[:, i] = np.searchsorted(cdf, U[:, i], side="left")
    k = counts[:, i]
    sev = np.exp(rng.normal(math.log(median), sigma, size=(N, KMAX)))
    mask = np.arange(KMAX)[None, :] < k[:, None]
    loss[:, i] = (sev * mask).sum(axis=1)


def rankdata(a):
    order = np.argsort(a, kind="mergesort")
    ranks = np.empty(len(a), dtype=float)
    ranks[order] = np.arange(1, len(a) + 1, dtype=float)
    sa = np.asarray(a)[order]
    i = 0
    while i < len(a):
        j = i
        while j + 1 < len(a) and sa[j + 1] == sa[i]:
            j += 1
        if j > i:
            ranks[order[i:j + 1]] = (i + 1 + j + 1) / 2.0
        i = j + 1
    return ranks


def spearman(a, b):
    ra = rankdata(a); rb = rankdata(b)
    ra -= ra.mean(); rb -= rb.mean()
    return float((ra @ rb) / math.sqrt((ra @ ra) * (rb @ rb)))


print(f"Iterations: {N:,}   Seed: {SEED}   Copula rho: {RHO}\n")
print(f"{'Scenario':<44}{'P(>=1)':>8}{'95th pct':>14}{'99th pct':>14}")
print("-" * 80)
for i, (name, p, _, _) in enumerate(scenarios):
    prob = (counts[:, i] > 0).mean()
    p95 = np.percentile(loss[:, i], 95)
    p99 = np.percentile(loss[:, i], 99)
    print(f"{name:<44}{prob:>7.1%}{'EUR ' + format(p95, ',.0f'):>14}"
          f"{'EUR ' + format(p99, ',.0f'):>14}")

q = (counts[:, 0] + counts[:, 1]) > 0
total = loss.sum(axis=1)
print("-" * 80)
print(f"P(any quality-loss event in 1 yr)      : {q.mean():.1%}")
print(f"P(any supply-disruption event in 1 yr) : "
      f"{((counts[:, 2] + counts[:, 3] + counts[:, 4] + counts[:, 5]) > 0).mean():.1%}")
print(f"P(any loss event across all scenarios) : "
      f"{(counts.sum(axis=1) > 0).mean():.1%}")
print(f"Aggregate 95th-percentile annual loss  : EUR {np.percentile(total, 95):,.0f}")
print(f"Aggregate 99th-percentile annual loss  : EUR {np.percentile(total, 99):,.0f}")
print(f"Aggregate mean annual loss             : EUR {total.mean():,.0f}")

qloss = loss[:, 0] + loss[:, 1]
sloss = loss[:, 2] + loss[:, 3] + loss[:, 4] + loss[:, 5]
print(f"Quality aggregate 95th / 99th pct       : EUR {np.percentile(qloss, 95):,.0f} / EUR {np.percentile(qloss, 99):,.0f}")
print(f"Supply  aggregate 95th / 99th pct       : EUR {np.percentile(sloss, 95):,.0f} / EUR {np.percentile(sloss, 99):,.0f}")
print("\nShare of aggregate-loss variance by scenario:")
var_total = total.var()
for i, (name, _, _, _) in enumerate(scenarios):
    share = np.cov(loss[:, i], total)[0, 1] / var_total
    print(f"  {name:<44}{share:>7.1%}")
print(f"  {'(cyber + supplier combined)':<44}"
      f"{np.cov(loss[:, 2] + loss[:, 3], total)[0, 1] / var_total:>7.1%}")

print(f"\nAchieved rank correlation (cyber vs logistics): "
      f"{spearman(counts[:, 2], counts[:, 4]):.2f}")
